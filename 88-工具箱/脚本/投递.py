# -*- coding: utf-8 -*-
"""投递共用：把正件落发起人出件箱，往接收人收件箱放指向消息。"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from 共用 import 公共区根, 写文件

动作类型 = {"协同单": "来单", "回执": "回执", "退回单": "退回"}


def 投递(后缀, 发起, 接收, 主题, 正文, 日期八位):
    文件名 = "%s-%s-%s-%s-%s.md" % (日期八位, 发起, 接收, 主题, 后缀)
    正件 = os.path.join(公共区根(), "04-交换区", 发起, "出件箱", 文件名)
    写文件(正件, 正文)
    指向 = "指向-" + 文件名
    指向文 = "正件路径：04-交换区/%s/出件箱/%s\n动作类型：%s\n日期：%s\n" % (
        发起, 文件名, 动作类型.get(后缀, 后缀), 日期八位)
    写文件(os.path.join(公共区根(), "04-交换区", 接收, "收件箱", 指向), 指向文)
    return 文件名
